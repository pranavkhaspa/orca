// Copy for the landing hero and the guided tour.
//
// Kept apart from i18n.ts, which translates the result chrome. That file's
// vocabulary is about a verdict that already exists; this one is about a person
// who has not asked anything yet, which is a different tone and a different
// set of sentences. Splitting them means the tour can be rewritten without
// touching a single label in the results.
//
// A missing locale falls back to English per-field rather than dropping the
// tour, on the same reasoning as i18n.ts: an untranslated sentence is a
// disappointment, an undefined one is a blank screen.

