type MetricKey =
  | 'wave'
  | 'wavePeriod'
  | 'swell'
  | 'tide'
  | 'sst'
  | 'wind'
  | 'gust'
  | 'rain'
  | 'cloud'
  | 'lightning'
  | 'anomaly';

type UnitKey = 'm' | 's' | 'kmh' | 'c' | 'km';

// The API names degraded inputs with machine keys. Only the two that have no
// natural word in the existing vocabulary need translating; 'marine' and
// 'weather' reuse the already-translated Sea state / Atmosphere headings, and
// the snapshot variants append the existing snapshot word.
type DegradedKey = 'incois' | 'llm';

