export function makeT(lang: string): Strings {
  const base = STRINGS.en;
  const table = (STRINGS as Record<string, Strings>)[lang];
  if (!table) return base;
  // Merge so a future partial translation cannot produce undefined labels.
  return {
    ...base,
    ...table,
    metrics: { ...base.metrics, ...table.metrics },
    units: { ...base.units, ...table.units },
  }
}

export type T = ReturnType<typeof makeT>;

